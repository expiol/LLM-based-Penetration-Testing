# 当前语言（默认英文）
_current_language: str = "en"


def set_language(lang: str):
    """设置当前语言"""
    global _current_language
    if lang in TRANSLATIONS:
        _current_language = lang
    else:
        raise ValueError(f"Unsupported language: {lang}. Supported: {list(TRANSLATIONS.keys())}")


def get_language() -> str:
    """获取当前语言"""
    return _current_language


def t(key: str, **kwargs) -> str:
    """
    翻译函数
    用法: t("app.title") 或 t("log.reason", reason="test")
    """
    translations = TRANSLATIONS.get(_current_language, TRANSLATIONS["en"])
    text = translations.get(key, key)
    
    # 格式化参数
    if kwargs:
        try:
            text = text.format(**kwargs)
        except KeyError:
            # 如果格式化失败，返回原始文本
            pass
    
    return text


def load_language_from_config(config_path: Optional[Path] = None) -> str:
    """从配置文件加载语言设置"""
    if config_path is None:
        config_path = Path(__file__).parent.parent.parent / "configs" / "llm_runtime.json"
    
    try:
        if config_path.exists():
            with open(config_path, "r", encoding="utf-8") as f:
                config = json.load(f)
                lang = config.get("ui", {}).get("language", "en")
                set_language(lang)
                return lang
    except Exception:
        pass
    
    # 默认返回英文
    set_language("en")
    return "en"

